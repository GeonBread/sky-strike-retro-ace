    randomOrder(count) {
        const order = Array.from({ length: count }, (_, index) => index);
        for (let index = order.length - 1; index > 0; index--) {
            const swapIndex = Math.floor(Math.random() * (index + 1));
            [order[index], order[swapIndex]] = [order[swapIndex], order[index]];
        }
        return order;
    }
    updateKakao(dt, data) {
        if (data.phase === 'appOpening') {
            data.phaseTime -= dt;
            data.openProgress = this.ease(1 - data.phaseTime / 0.78);
            this.adapter.clearPlayerBullets?.();
            if (data.phaseTime <= 0) {
                data.openProgress = 1;
                data.phase = 'chatList';
                data.phaseTime = 1.35;
                this.message('채팅방 목록이 공격 형태로 분리됩니다.');
            }
            return;
        }
        if (data.phase === 'chatList') {
            data.phaseTime -= dt;
            if (data.phaseTime <= 0) {
                data.phase = 'separating';
                data.phaseTime = 0.58;
                for (const room of data.rooms) {
                    room.state = 'separating';
                    room.startX = room.x;
                    room.startY = room.y;
                    room.startScale = 1;
                    room.startRotation = 0;
                }
                this.message('채팅방 목록이 원래 자리에서 분리됩니다.');
            }
            return;
        }
        if (data.phase === 'separating') {
            data.phaseTime -= dt;
            const progress = this.ease(1 - data.phaseTime / 0.58);
            data.panelAlpha = 1 - 0.58 * progress;
            for (const room of data.rooms) {
                room.x = room.startX + room.detachOffsetX * progress;
                room.y = room.startY + room.detachOffsetY * progress - Math.sin(progress * Math.PI) * this.Y(3);
                room.scale = 1 - 0.05 * progress;
                room.rotation = 0;
            }
            if (data.phaseTime <= 0) {
                data.phase = 'rotatingAligning';
                data.phaseTime = 1.18;
                for (const room of data.rooms) {
                    room.state = 'rotatingAligning';
                    room.startX = room.x;
                    room.startY = room.y;
                    room.startScale = room.scale;
                    room.startRotation = room.rotation;
                }
                this.message('분리된 채팅방이 회전하며 상단에 정렬됩니다.');
            }
            return;
        }
        if (data.phase === 'rotatingAligning') {
            data.phaseTime -= dt;
            const progress = this.ease(1 - data.phaseTime / 1.18);
            data.panelAlpha = 0.42 * (1 - progress);
            for (const room of data.rooms) {
                room.x = room.startX + (room.targetX - room.startX) * progress;
                room.y = room.startY + (room.targetY - room.startY) * progress;
                room.scale = room.startScale + (data.detachedScale - room.startScale) * progress;
                room.rotation = room.startRotation + (Math.PI / 2 - room.startRotation) * progress;
            }
            if (data.phaseTime <= 0) {
                data.panelAlpha = 0;
                data.phase = 'lined';
                data.phaseTime = 0.38;
                for (const room of data.rooms) {
                    room.state = 'lined';
                    room.x = room.targetX;
                    room.y = room.targetY;
                    room.scale = data.detachedScale;
                    room.rotation = Math.PI / 2;
                }
            }
            return;
        }
        if (data.phase === 'lined') {
            data.phaseTime -= dt;
            if (data.phaseTime <= 0) {
                data.phase = 'aiming';
                data.phaseTime = 0.92;
                for (const room of data.rooms)
                    room.state = 'aiming';
                this.message('모든 채팅방이 발사 직전까지 플레이어를 추적합니다.');
            }
            return;
        }
        if (data.phase === 'aiming') {
            data.phaseTime -= dt;
            this.trackKakaoRooms(data);
            if (data.phaseTime <= 0) {
                data.phase = 'launching';
                data.launchIndex = 0;
                data.launchOrder = this.randomOrder(data.rooms.length);
                data.launchTimer = 0.55;
                for (const room of data.rooms)
                    room.state = 'ready';
                this.message('채팅방 발사 순서가 무작위로 결정되었습니다.');
            }
            return;
        }
        if (data.phase === 'launching') {
            this.trackKakaoRooms(data);
            const player = this.player();
            data.launchTimer -= dt;
            if (data.launchIndex < data.launchOrder.length && data.launchTimer <= 0) {
                const room = data.rooms[data.launchOrder[data.launchIndex]];
                room.state = 'warning';
                room.warning = 0.42;
                room.hit = false;
                room.life = 8;
                room.trail.length = 0;
                this.addRing(room.x + room.w / 2, room.y + room.h / 2, '#ff5a36', this.X(64), 0.22, this.X(4));
                data.launchIndex++;
                data.launchTimer = 0.57;
            }
            for (const room of data.rooms) {
                if (room.state === 'warning') {
                    room.warning -= dt;
                    if (room.warning <= 0) {
                        room.state = 'flying';
                        const speed = this.X(730);
                        room.vx = Math.cos(room.rotation) * speed;
                        room.vy = Math.sin(room.rotation) * speed;
                    }
                }
                else if (room.state === 'flying') {
                    room.trailTimer -= dt;
                    if (room.trailTimer <= 0) {
                        room.trail.push({ x: room.x, y: room.y, rotation: room.rotation, scale: room.scale, life: 0.18 });
                        room.trailTimer = 0.035;
                    }
                    room.x += room.vx * dt;
                    room.y += room.vy * dt;
                    room.life -= dt;
                    if (this.options.collisionEnabled &&
                        !room.hit &&
                        this.rotatedRectCircleHit(room.x + room.w / 2, room.y + room.h / 2, room.w * room.scale, room.h * room.scale, room.rotation, player)) {
                        room.hit = true;
                        this.adapter.damagePlayer(18);
                    }
                    if (room.x < -this.X(420) || room.x > this.W + this.X(420) ||
                        room.y < -this.Y(420) || room.y > this.H + this.Y(420) ||
                        room.life <= 0)
                        room.state = 'gone';
                }
                for (const trail of room.trail)
                    trail.life -= dt;
                room.trail = room.trail.filter(trail => trail.life > 0);
            }
            const allLaunched = data.launchIndex >= data.launchOrder.length;
            const allGone = data.rooms.every(room => room.state === 'gone');
            if (allLaunched && allGone) {
                data.salvo++;
                if (data.salvo >= this.options.kakaoSalvos) {
                    this.completePhase();
                }
                else {
                    this.prepareKakaoSalvo(data);
                    data.phase = 'appOpening';
                    data.phaseTime = 0.58;
                    data.openProgress = 0;
                    this.message(`카톡 채팅 미사일 ${data.salvo + 1}차 공격`);
                }
            }
        }
    }
    trackKakaoRooms(data) {
        const player = this.player();
        for (const room of data.rooms) {
            if (!['aiming', 'ready', 'warning'].includes(room.state))
                continue;
            const cx = room.x + room.w / 2;
            const cy = room.y + room.h / 2;
            const target = Math.atan2(player.y - cy, player.x - cx);
            let delta = target - room.rotation;
            while (delta > Math.PI)
                delta -= Math.PI * 2;
            while (delta < -Math.PI)
                delta += Math.PI * 2;
            room.rotation += delta * 0.18;
        }
    }
