    circleHit(a, b) {
        const ar = a.r ?? 0;
        const br = b.r ?? 0;
        return (a.x - b.x) ** 2 + (a.y - b.y) ** 2 <= (ar + br) ** 2;
    }
    rotatedRectCircleHit(cx, cy, width, height, angle, circle) {
        const dx = circle.x - cx;
        const dy = circle.y - cy;
        const c = Math.cos(-angle);
        const s = Math.sin(-angle);
        const lx = dx * c - dy * s;
        const ly = dx * s + dy * c;
        const nx = clamp(lx, -width / 2, width / 2);
        const ny = clamp(ly, -height / 2, height / 2);
        const r = circle.r ?? 0;
        return (lx - nx) ** 2 + (ly - ny) ** 2 <= r ** 2;
    }
