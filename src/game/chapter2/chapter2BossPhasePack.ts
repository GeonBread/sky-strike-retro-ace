    roundedPath(ctx, x, y, width, height, radius) {
        const r = Math.min(radius, width / 2, height / 2);
        ctx.beginPath();
        ctx.moveTo(x + r, y);
        ctx.lineTo(x + width - r, y);
        ctx.quadraticCurveTo(x + width, y, x + width, y + r);
        ctx.lineTo(x + width, y + height - r);
        ctx.quadraticCurveTo(x + width, y + height, x + width - r, y + height);
        ctx.lineTo(x + r, y + height);
        ctx.quadraticCurveTo(x, y + height, x, y + height - r);
        ctx.lineTo(x, y + r);
        ctx.quadraticCurveTo(x, y, x + r, y);
        ctx.closePath();
    }
    roundedRect(ctx, x, y, width, height, radius, fill, stroke) {
        this.roundedPath(ctx, x, y, width, height, radius);
        ctx.fillStyle = fill;
        ctx.fill();
        if (stroke) {
            ctx.strokeStyle = stroke;
            ctx.lineWidth = 1;
            ctx.stroke();
        }
    }
    text(ctx, value, x, y, size, color, align = 'center', weight = 800, maxWidth) {
        ctx.font = `${weight} ${size * this.scale}px Pretendard, Noto Sans KR, sans-serif`;
        ctx.textAlign = align;
        ctx.textBaseline = 'middle';
        ctx.fillStyle = color;
        if (maxWidth)
            ctx.fillText(value, x, y, maxWidth);
        else
            ctx.fillText(value, x, y);
    }
    wrapText(ctx, value, maxWidth, size, weight) {
        ctx.font = `${weight} ${size * this.scale}px Pretendard, Noto Sans KR, sans-serif`;
        const lines = [];
        let line = '';
        for (const character of value) {
            const test = line + character;
            if (ctx.measureText(test).width > maxWidth && line) {
                lines.push(line);
                line = character;
            }
            else {
                line = test;
            }
        }
        if (line)
            lines.push(line);
        return lines;
    }
    fitLabel(ctx, value, maxWidth, size, weight) {
        ctx.font = `${weight} ${size * this.scale}px Pretendard, Noto Sans KR, sans-serif`;
        if (ctx.measureText(value).width <= maxWidth)
            return value;
        let result = value;
        while (result.length > 1 && ctx.measureText(`${result}…`).width > maxWidth)
            result = result.slice(0, -1);
        return `${result}…`;
    }
    drawAvatar(ctx, avatar, x, y) {
        const palette = ['#111111', '#8fc4eb', '#8ed7df', '#73c8bf', '#ffd7a4', '#76818b', '#c6a58f', '#94a8bf', '#111111', '#8ed7df'];
        ctx.save();
        ctx.fillStyle = palette[avatar % palette.length];
        ctx.beginPath();
        ctx.arc(x, y, this.X(21), 0, Math.PI * 2);
        ctx.fill();
        if (avatar % 4 === 0) {
            this.text(ctx, 'EO', x, y, 9, '#ffffff', 'center', 900);
        }
        else {
            ctx.fillStyle = 'rgba(255,255,255,.82)';
            ctx.beginPath();
            ctx.arc(x, y - this.Y(5), this.X(6), 0, Math.PI * 2);
            ctx.fill();
            ctx.beginPath();
            ctx.arc(x, y + this.Y(12), this.X(12), Math.PI, Math.PI * 2);
            ctx.fill();
        }
        ctx.restore();
    }
