    getReportWordLayout(data) {
        let remaining = Math.floor(data.typedChars);
        let y = this.Y(246);
        const left = this.X(154);
        const maxWidth = this.X(492);
        const tokens = [];
        for (let paragraphIndex = 0; paragraphIndex < data.paragraphs.length; paragraphIndex++) {
            const paragraph = data.paragraphs[paragraphIndex];
            if (remaining <= 0)
                break;
            const shown = paragraph.text.slice(0, remaining);
            remaining -= shown.length;
            const weight = paragraph.bold ? 800 : 500;
            const paragraphComplete = shown.length === paragraph.text.length;
            const lines = this.wrapText(this.ctx, shown, maxWidth, paragraph.size, weight);
            for (let lineIndex = 0; lineIndex < lines.length; lineIndex++) {
                const line = lines[lineIndex];
                this.ctx.font = `${weight} ${paragraph.size * this.scale}px Pretendard, Noto Sans KR, sans-serif`;
                const lineWidth = this.ctx.measureText(line).width;
                const startX = paragraph.center ? this.W / 2 - lineWidth / 2 : left;
                const matches = line.matchAll(/[가-힣A-Za-z0-9]+/g);
                for (const match of matches) {
                    const value = match[0];
                    if (value.length < 2)
                        continue;
                    const prefixWidth = this.ctx.measureText(line.slice(0, match.index)).width;
                    const wordWidth = this.ctx.measureText(value).width;
                    tokens.push({
                        key: `${paragraphIndex}:${lineIndex}:${match.index}:${value}`,
                        text: value,
                        x: startX + prefixWidth + wordWidth / 2,
                        y,
                        w: wordWidth,
                        h: this.Y(paragraph.size + 8),
                        size: paragraph.size,
                        weight,
                        complete: paragraphComplete
                    });
                }
                y += this.Y(paragraph.size + 9);
            }
            y += this.Y(paragraph.gap);
            if (shown.length < paragraph.text.length)
                break;
        }
        return tokens;
    }
